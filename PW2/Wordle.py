def eqaWord(first:str, second:str):
    lE = [[0]*5 for _ in range(5)]
    for i in range(5):
        if not second[i] in first:continue
        for j in range(5):
            if second[i] == first[j]:
                if i == j:
                    lE[i][j]=2
                else:
                    lE[i][j]=1
    
    return list(map((lambda x: max(x)),lE))

